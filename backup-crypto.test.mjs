import {webcrypto} from 'node:crypto';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const context={window:{},crypto:webcrypto,TextEncoder,TextDecoder,btoa,atob,Uint8Array};
vm.runInNewContext(await readFile('backup-crypto.js','utf8'),context);
const B=context.window.BAP_BACKUP,p='Una contraseña larga de prueba';
const source={format:'bap-gastos-v1',expenses:[{id:'synthetic',merchant:'Prueba S/ dólares',amount:123.45}]};
const encrypted=await B.encrypt(source,p);
assert(!JSON.stringify(encrypted).includes('merchant'));
assert.equal(JSON.stringify(await B.decrypt(encrypted,p)),JSON.stringify(source));
await assert.rejects(B.decrypt(encrypted,'Contraseña incorrecta'));
const changed={...encrypted,ciphertext:(encrypted.ciphertext[0]==='A'?'B':'A')+encrypted.ciphertext.slice(1)};
await assert.rejects(B.decrypt(changed,p));
await assert.rejects(B.decrypt({...encrypted,iterations:1},p));
await assert.rejects(B.encrypt(source,'short'));
const second=await B.encrypt(source,p);assert.notEqual(second.ciphertext,encrypted.ciphertext);
assert.equal(JSON.stringify(await B.open(JSON.stringify(source))),JSON.stringify(source));
console.log('Encrypted backup: roundtrip, wrong password, tampering, KDF bounds, randomization and legacy import passed.');
