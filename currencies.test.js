const assert = require('node:assert/strict');
const M = require('./finance-model.js');
const X = require('./xlsx.js');
const id = n => `20000000-0000-4000-8000-${String(n).padStart(12,'0')}`;
const record = (n,kind,data) => ({id:id(n),kind,data:{date:'2026-10-01',...data}});
const pen = record(1,'debt',{name:'Deuda heredada',type:'loan',balance:500,minimum:50,tea:0});
const usd = record(2,'debt',{name:'Préstamo USD',currency:'USD',type:'loan',balance:600,minimum:0,tea:0});
const schedule = record(3,'charge',{debt_id:usd.id,currency:'USD',schedule_only:true,name:'Cuotas USD',amount:600,installments:6,paid_before:0,first_due:'2026-10-20',tea:0});
const payment = record(4,'payment',{debt_id:usd.id,schedule_id:schedule.id,currency:'USD',amount:40,principal:40,date:'2026-10-10'});
const rows = [pen,usd,schedule,payment,record(5,'income',{name:'Sueldo PEN',amount:1500}),record(6,'income',{name:'Ingreso USD',currency:'USD',amount:300}),record(7,'settings',{expenses:500,reserve:50}),record(8,'settings',{currency:'USD',expenses:20,reserve:10})];
assert(rows.every(M.validRecord));
const soles = M.analyze(rows,[],'2026-10','2026-10-20');
const dollars = M.analyze(rows,[],'2026-10','2026-10-20','USD');
assert.equal(soles.currency,'PEN');
assert.equal(soles.totalDebt,500);
assert.equal(soles.earned,1500);
assert.equal(soles.payments,0);
assert.equal(dollars.totalDebt,560);
assert.equal(dollars.earned,300);
assert.equal(dollars.payments,40);
assert.equal(dollars.settings.expenses,20);
assert.equal(dollars.debts[0].schedules[0].items[0].remaining,60);
assert.equal(dollars.debts[0].schedules[0].items[0].status,'Parcial');
const wrongPayment = {...payment,data:{...payment.data,currency:'PEN',principal:4000,amount:4000}};
assert.equal(M.balance(usd,[usd,wrongPayment],[]),600);
assert.equal(M.schedules(usd,[usd,schedule,wrongPayment],[],'2026-10','2026-10-20')[0].paidCount,0);
const cash = [{id:id(10),date:'2026-10-03',amount:10},{id:id(11),date:'2026-10-03',amount:25,currency:'USD'}];
assert.equal(M.analyze(rows,cash,'2026-10','2026-10-20').purchases,10);
assert.equal(M.analyze(rows,cash,'2026-10','2026-10-20','USD').purchases,25);
assert.equal(M.validRecord(record(20,'income',{name:'Inválido',amount:1,currency:'EUR'})),false);
assert.equal(M.validRecord(record(20,'income',{name:'Inválido',amount:1,currency:null})),false);
assert.throws(()=>M.analyze(rows,[],'2026-10','2026-10-20','EUR'));
assert.equal(soles.cashBudget,500);
assert.equal(dollars.cashBudget,20);
(async()=>{
  const xlsx = X.create([{date:'2026-10-01',merchant:'USD',category:'Otros',payment:'Efectivo',amount:25,currency:'USD'}]);
  const text = new TextDecoder().decode(await xlsx.arrayBuffer());
  assert(text.includes('Moneda') && text.includes('USD'));
  assert(!text.includes('S/ '));
  assert(text.includes('<v>25</v>'));
  console.log('Currency scenarios passed: separate ledgers, legacy PEN, USD installments, cash flow and Excel.');
})();
