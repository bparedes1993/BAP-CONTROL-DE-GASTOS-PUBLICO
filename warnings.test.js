const assert = require('node:assert/strict');
const M = require('./finance-model');
const id = n => `20000000-0000-4000-8000-${String(n).padStart(12,'0')}`;
const debt = {id:id(1),kind:'debt',data:{name:'Préstamo',type:'loan',balance:600,date:'2026-10-01',tea:0,minimum:0}};
const plan = {id:id(2),kind:'charge',data:{name:'Cuotas',debt_id:debt.id,schedule_only:true,amount:600,installments:6,paid_before:0,first_due:'2026-10-20',tea:0,date:'2026-10-01'}};
const payment = {id:id(3),kind:'payment',data:{debt_id:debt.id,amount:100,principal:100,date:'2026-10-10'}};
const settings = {id:id(4),kind:'settings',data:{income:1000,expenses:200,strategy:'snowball'}};
const run = (...payments) => M.analyze([debt,plan,settings,...payments],[],'2026-10','2026-10-20');
let a = run(payment);
assert.equal(a.paymentsMissingSchedule.length,1);
assert.equal(a.debts[0].schedules[0].paidCount,0);
a=run({...payment,data:{...payment.data,schedule_id:plan.id}});
assert.equal(a.paymentsMissingSchedule.length,0);
assert.equal(a.debts[0].schedules[0].paidCount,1);
assert.equal(a.pending,0);
assert(!a.warnings.some(w=>w.includes('vencimientos')));
a=run({...payment,data:{...payment.data,payment_allocation:'other'}});
assert.equal(a.paymentsMissingSchedule.length,0);
assert.equal(a.debts[0].schedules[0].paidCount,0);
assert(M.validRecord({...payment,data:{...payment.data,payment_allocation:'other'}}));
assert(!M.validRecord({...payment,data:{...payment.data,schedule_id:plan.id,payment_allocation:'other'}}));
a=run({...payment,data:{...payment.data,date:'2026-09-01',principal:null}});
assert.equal(a.paymentsMissingSchedule.length,0);
assert.equal(a.paymentsMissingCapital.length,0);
a=run({...payment,data:{...payment.data,schedule_id:plan.id,principal:null}});
assert.equal(a.paymentsMissingSchedule.length,0);
assert.equal(a.paymentsMissingCapital.length,1);
assert.equal(a.debts[0].balance,600);
assert.equal(a.planReady,false);
for (const p of [{...payment,deleted:true},{...payment,data:{...payment.data,currency:'USD'}},{...payment,data:{...payment.data,debt_id:id(99)}}]) {
  assert.equal(run(p).paymentsMissingSchedule.length,0);
}
a=M.analyze([debt,plan],[],'2026-10','2026-10-20');
assert(a.deficit>0);
assert.equal(a.deficitConfirmed,false);
assert(!a.warnings.some(w=>w.startsWith('El presupuesto no cubre')));
a=M.analyze([debt,plan,{...settings,data:{...settings.data,income:50}}],[],'2026-10','2026-10-20');
assert.equal(a.deficitConfirmed,true);
console.log('Warning regression scenarios passed: assignment, reconciliation, capital, currency and incomplete budgets.');
